"""Export the built-in OpenAI proxy contract for the Fern API reference."""

from __future__ import annotations

import argparse
import difflib
from pathlib import Path

import yaml

SPEC_PATH = Path(__file__).resolve().parents[1] / "fern" / "proxy-openapi.yml"
HEADER = """# Generated by scripts/export_proxy_openapi.py. Do not edit directly.
# Documentation additions belong in fern/proxy-openapi-overlay.yml.

"""


def proxy_openapi() -> dict:
    """Describe a deterministic example deployment without starting the proxy."""
    from nemoguardrails.server.experimental._application import create_proxy_application
    from nemoguardrails.server.experimental.providers.openai.integration import create_openai_integration

    provider = create_openai_integration(base_url="https://api.openai.com/v1")
    return create_proxy_application(providers=[provider]).openapi()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=SPEC_PATH)
    parser.add_argument("--check", action="store_true", help="Check for stale output without writing it")
    args = parser.parse_args()
    expected = HEADER + yaml.safe_dump(proxy_openapi(), sort_keys=True, allow_unicode=True, width=100)
    if args.check:
        actual = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if actual != expected:
            print(
                "".join(
                    difflib.unified_diff(
                        actual.splitlines(True),
                        expected.splitlines(True),
                        fromfile=str(args.output),
                        tofile="generated proxy OpenAPI",
                    )
                ),
                end="",
            )
            print("Proxy OpenAPI specification is stale. Run: make docs-fern-generate-openapi")
            return 1
        print(f"Proxy OpenAPI specification is current: {args.output}")
        return 0
    args.output.write_text(expected, encoding="utf-8")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
