"""Export the built-in OpenAI proxy contract for the Fern API reference."""

from __future__ import annotations

import argparse
import difflib
from pathlib import Path

import yaml

from scripts.proxy_guard_contract_docs import policy_badge, render_contract_page

SPEC_PATH = Path(__file__).resolve().parents[1] / "fern" / "proxy-openapi.yml"
HEADER = """# Generated by scripts/export_proxy_openapi.py. Do not edit directly.
# Documentation additions belong in fern/proxy-openapi-overlay.yml.

"""


def proxy_openapi() -> dict:
    """Describe a deterministic example deployment without starting the proxy."""
    from nemoguardrails.server.experimental._application import create_proxy_application
    from nemoguardrails.server.experimental.providers.openai.integration import create_openai_integration

    provider = create_openai_integration(base_url="https://api.openai.com/v1")
    return create_proxy_application(providers=[provider]).openapi()


def describe_guard_fields(schema: dict) -> None:
    """Explain exported field policy without changing validation assertions."""
    policy = schema.get("x-nemo-guardrails", {})
    classification = policy.get("classification")
    if policy.get("gate") == "disabled":
        explanation = "Omit this field or set it to `null`; non-null values are rejected."
    elif classification == "opaque":
        explanation = (
            "Forwarded without inspecting or validating its value or nested contents. "
            "Provider requirements still apply."
        )
    elif classification == "guarded":
        explanation = (
            "Text selected for input checks when enabled in the Rails configuration."
            if policy.get("subject")
            else "Container leading to text selected for input checks when enabled in the Rails configuration."
        )
    elif classification == "constrained":
        explanation = "The proxy enforces the declared value and shape restrictions."
    else:
        explanation = ""
    if explanation:
        badge = policy_badge(schema)
        schema["description"] = "\n\n".join(filter(None, (f"{badge} {explanation}", schema.get("description"))))
    if "properties" in schema:
        schema["description"] = "\n\n".join(
            filter(
                None,
                (
                    schema.get("description"),
                    "Unlisted fields and case aliases of declared fields are rejected by default.",
                ),
            )
        )
    for child in schema.get("properties", {}).values():
        describe_guard_fields(child)
    if isinstance(schema.get("items"), dict):
        describe_guard_fields(schema["items"])
    for keyword in ("anyOf", "oneOf", "allOf"):
        for child in schema.get(keyword, []):
            describe_guard_fields(child)


def reference_openapi() -> dict:
    """Add readable guard policy to the example deployment's request schemas."""
    document = proxy_openapi()
    for path in document["paths"].values():
        for operation in path.values():
            schema = operation["requestBody"]["content"]["application/json"]["schema"]
            schema["description"] = (
                "Request fields describe the proxy guard boundary. Provider requirements apply separately."
            )
            describe_guard_fields(schema)
    return document


def guard_contract_pages() -> dict[str, str]:
    """Render live exports from the same built-in operation catalog as the example app."""
    from nemoguardrails.server.experimental.provider.contract_export import export_guard_contract
    from nemoguardrails.server.experimental.providers.openai.integration import create_openai_integration

    provider = create_openai_integration(base_url="https://api.openai.com/v1")
    pages = {}
    for endpoint in provider.endpoints:
        assert endpoint.contract_name is not None
        slug = endpoint.contract_name.replace("_", "-")
        pages[slug + ".mdx"] = render_contract_page(export_guard_contract(endpoint), slug)
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=SPEC_PATH)
    parser.add_argument("--contracts-output", type=Path, help="Contract page directory (default: beside --output)")
    parser.add_argument("--check", action="store_true", help="Check for stale output without writing it")
    args = parser.parse_args()
    contracts_output = args.contracts_output or args.output.parent / "proxy-guard-contracts"
    outputs = {
        args.output: HEADER + yaml.safe_dump(reference_openapi(), sort_keys=True, allow_unicode=True, width=100),
        **{contracts_output / name: page for name, page in guard_contract_pages().items()},
    }
    if args.check:
        stale = False
        for output, expected in outputs.items():
            actual = output.read_text(encoding="utf-8") if output.exists() else ""
            if actual == expected:
                continue
            stale = True
            print(
                "".join(
                    difflib.unified_diff(
                        actual.splitlines(True),
                        expected.splitlines(True),
                        fromfile=str(output),
                        tofile="generated proxy reference",
                    )
                ),
                end="",
            )
        if stale:
            print("Proxy reference artifacts are stale. Run: make docs-fern-generate-openapi")
            return 1
        print(f"Proxy reference artifacts are current: {args.output}")
        return 0
    for output, expected in outputs.items():
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(expected, encoding="utf-8")
        print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
