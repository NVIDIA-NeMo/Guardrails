"""Export the stable FastAPI server contract used by the Fern API reference."""

from __future__ import annotations

import argparse
import difflib
import os
from pathlib import Path

import yaml

SPEC_PATH = Path(__file__).resolve().parents[1] / "fern" / "openapi.yml"
HEADER = """# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: Apache-2.0
#
# Generated by scripts/export_openapi.py. Do not edit directly.
# Documentation additions belong in fern/openapi-overlay.yml.

"""


def main() -> int:
    """Generate the build artifact, or verify an existing local export."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=SPEC_PATH, help="Output YAML path")
    parser.add_argument("--check", action="store_true", help="Fail if the output needs regeneration; do not write it")
    args = parser.parse_args()

    # Exclude the optional chat UI so installed extras cannot change the contract.
    os.environ["NEMO_GUARDRAILS_DISABLE_CHAT_UI"] = "true"
    from nemoguardrails.server.api import app

    expected = HEADER + yaml.safe_dump(app.openapi(), sort_keys=True, allow_unicode=True, width=100)
    if args.check:
        actual = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if actual != expected:
            print(
                "".join(
                    difflib.unified_diff(
                        actual.splitlines(True),
                        expected.splitlines(True),
                        fromfile=str(args.output),
                        tofile="generated OpenAPI",
                    )
                ),
                end="",
            )
            print("OpenAPI specification is stale. Run: uv run --locked python scripts/export_openapi.py")
            return 1
        print(f"OpenAPI specification is current: {args.output}")
        return 0

    args.output.write_text(expected, encoding="utf-8")
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
