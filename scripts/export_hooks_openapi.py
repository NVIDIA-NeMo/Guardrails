"""Export the hooks server contract for the Fern API reference."""

from __future__ import annotations

import argparse
import asyncio
import difflib
import json
from pathlib import Path
from typing import Any

import yaml
from fastapi.openapi.utils import get_openapi

from nemoguardrails.server.hooks.adapters import ADAPTERS
from nemoguardrails.server.hooks.app import _router

SPEC_PATH = Path(__file__).resolve().parents[1] / "fern" / "hooks-openapi.yml"
HEALTH_DOCS_PATH = Path(__file__).resolve().parents[1] / "docs" / "reference" / "hooks-server-api" / "_generated"
HEADER = """# Generated by scripts/export_hooks_openapi.py. Do not edit directly.
# Documentation additions belong in fern/hooks-openapi-overlay.yml.

"""


def hooks_openapi() -> dict:
    """Describe the registered routes and the models their adapters actually validate."""
    spec = get_openapi(title="NeMo Guardrails Hooks API", version="0.1.0", routes=_router.routes)
    schemas = spec.setdefault("components", {}).setdefault("schemas", {})
    schemas.update(
        {
            "PreToolUseDeny": {
                "type": "object",
                "required": ["hookSpecificOutput"],
                "additionalProperties": False,
                "properties": {
                    "hookSpecificOutput": {
                        "type": "object",
                        "required": ["hookEventName", "permissionDecision", "permissionDecisionReason"],
                        "additionalProperties": False,
                        "properties": {
                            "hookEventName": {"type": "string", "const": "PreToolUse"},
                            "permissionDecision": {"type": "string", "const": "deny"},
                            "permissionDecisionReason": {"type": "string"},
                        },
                    }
                },
            },
            "RelayAllow": {
                "type": "object",
                "required": ["decision"],
                "additionalProperties": False,
                "properties": {"decision": {"type": "string", "const": "allow"}},
            },
            "RelayDeny": {
                "type": "object",
                "required": ["decision", "reason"],
                "additionalProperties": False,
                "properties": {"decision": {"type": "string", "const": "deny"}, "reason": {"type": "string"}},
            },
            "HookError": {
                "type": "object",
                "required": ["error"],
                "properties": {
                    "error": {
                        "type": "object",
                        "required": ["message", "type", "param", "code"],
                        "properties": {
                            "message": {"type": "string"},
                            "type": {"type": "string"},
                            "param": {"type": ["string", "null"]},
                            "code": {"type": ["string", "null"]},
                        },
                    }
                },
            },
            "Health": {
                "type": "object",
                "required": ["status"],
                "properties": {"status": {"type": "string", "const": "pass"}},
            },
        }
    )
    error = {"content": {"application/json": {"schema": {"$ref": "#/components/schemas/HookError"}}}}
    for agent, adapter in ADAPTERS.items():
        model = adapter.request_model
        model_schema = model.model_json_schema(ref_template="#/components/schemas/{model}")
        schemas.update(model_schema.pop("$defs", {}))
        schemas[model.__name__] = model_schema
        if model.model_fields["tool_input"].annotation is Any:
            # Fern needs explicit JSON types to retain object-valued examples for Any.
            schemas[model.__name__]["properties"]["tool_input"]["anyOf"] = [
                {"type": "object", "additionalProperties": True},
                {"type": "array", "items": {}},
                {"type": "string"},
                {"type": "number"},
                {"type": "boolean"},
                {"type": "null"},
            ]
        operation = spec["paths"][f"/v1/hooks/{agent}"]["post"]
        operation["requestBody"] = {
            "required": True,
            "content": {"application/json": {"schema": {"$ref": f"#/components/schemas/{model.__name__}"}}},
        }
        allowed = (
            {"$ref": "#/components/schemas/RelayAllow"}
            if agent == "nemo-relay"
            else {"type": "object", "properties": {}, "additionalProperties": False}
        )
        denied = {"$ref": f"#/components/schemas/{'RelayDeny' if agent == 'nemo-relay' else 'PreToolUseDeny'}"}
        operation["responses"] = {
            "200": {
                "description": "Allow or deny decision",
                "content": {"application/json": {"schema": {"oneOf": [allowed, denied]}}},
            },
            "422": {"description": "Invalid request or unsupported event", **error},
            "500": {"description": "Check failed", **error},
            "503": {
                "description": "Admission queue full",
                "headers": {"Retry-After": {"description": "Retry delay in seconds", "schema": {"type": "string"}}},
                **error,
            },
        }
    for path in ("/v1/health", "/healthz"):
        spec["paths"][path]["get"]["responses"] = {
            "200": {
                "description": "Server is alive",
                "content": {"application/health+json": {"schema": {"$ref": "#/components/schemas/Health"}}},
            }
        }
    return spec


def health_pages(directory: Path) -> dict[Path, str]:
    """Render each registered health handler's actual response without starting the server."""
    pages = {}
    routes = {route.path: route for route in _router.routes}
    for path, slug, title in (
        ("/v1/health", "get-health", "Health Check"),
        ("/healthz", "get-healthz", "Health Check (Alias)"),
    ):
        response = asyncio.run(routes[path].endpoint())
        body = json.dumps(json.loads(response.body), ensure_ascii=False)
        pages[directory / f"{slug}.mdx"] = f'''---
title: "{title}"
sidebar-title: "{title}"
description: "Liveness health check for the Guardrails hooks server."
content:
  type: "reference"
---

```text
GET http://localhost:8100{path}
```

Shallow liveness check. The server validates its configuration before it accepts requests.
This check does not call a model.

The response is `{response.status_code}` with the `{response.media_type}` media type:

```json
{body}
```
'''
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=SPEC_PATH)
    parser.add_argument("--health-docs-dir", type=Path, help="Directory for generated health reference pages")
    parser.add_argument("--check", action="store_true", help="Check for stale output without writing it")
    args = parser.parse_args()
    expected = HEADER + yaml.safe_dump(hooks_openapi(), sort_keys=True, allow_unicode=True, width=100)
    outputs = {args.output: expected}
    health_dir = args.health_docs_dir or (HEALTH_DOCS_PATH if args.output == SPEC_PATH else None)
    if health_dir is not None:
        outputs.update(health_pages(health_dir))
    if args.check:
        stale = False
        for output, content in outputs.items():
            actual = output.read_text(encoding="utf-8") if output.exists() else ""
            if actual == content:
                continue
            stale = True
            print(
                "".join(
                    difflib.unified_diff(
                        actual.splitlines(True),
                        content.splitlines(True),
                        fromfile=str(output),
                        tofile="generated hooks reference",
                    )
                ),
                end="",
            )
        if stale:
            print("Hooks reference is stale. Run: make docs-fern-generate-openapi")
            return 1
        print("Hooks reference is current")
        return 0
    for output, content in outputs.items():
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(content, encoding="utf-8")
        print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
